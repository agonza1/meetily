def write_audio(output, samples, rate):
    subprocess.run(
        [
            "ffmpeg", "-nostdin", "-v", "error", "-y", "-f", "f32le",
            "-ar", str(rate), "-ac", "1", "-i", "pipe:0", "-ar", "16000",
            "-c:a", "pcm_s16le", str(output),
        ],
        input=np.asarray(samples, dtype="<f4").tobytes(),
        check=True,
    )


def mix(turns, rate, overlap):
    starts = []
    end = round(0.25 * rate)
    for samples, interrupts in turns:
        gap = -0.65 if overlap and interrupts else 0.36
        start = end + round(gap * rate)
        starts.append(start)
        end = max(end, start + len(samples))

    audio = np.zeros(end + round(0.4 * rate), dtype=np.float32)
    for (samples, _), start in zip(turns, starts, strict=True):
        audio[start:start + len(samples)] += samples
    return audio


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model", type=Path, required=True, help="Kokoro v1.0 ONNX file")
    parser.add_argument("--voices", type=Path, required=True, help="Kokoro v1.0 voice pack")
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()

    kokoro = Kokoro(str(args.model), str(args.voices))
    turns = []
    rate = None
    for speaker, text, interrupts in TURNS:
        voice, language, speed = VOICES[speaker]
        samples, sample_rate = kokoro.create(text, voice=voice, speed=speed, lang=language)
        if rate is not None and rate != sample_rate:
            raise ValueError("Kokoro returned mixed sample rates")
        rate = sample_rate
        peak = np.max(np.abs(samples))
        if not np.isfinite(peak) or peak <= 0:
            raise ValueError(f"Kokoro returned invalid audio for {speaker}")
        turns.append((samples * (0.42 / peak), interrupts))

    args.output.mkdir(parents=True, exist_ok=True)
    for name, overlap in (("clean", False), ("overlap", True)):
        samples = mix(turns, rate, overlap)
        write_audio(args.output / f"{name}.wav", samples, rate)
        print(f"{name}.wav: {len(samples) / rate:.1f} seconds")

    reference = "\n".join(text for _, text, _ in TURNS)
    (args.output / "reference.txt").write_text(reference + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
